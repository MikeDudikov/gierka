def native_queue_history(case):
    """Execute original queue updates for every publication, preserving ties/history."""
    publications = [publication for row in case['trace'] for publication in row['publications']]
    for publication in publications:
        require(len(publication['world']) == 2 and
                publication['depth'] == max(10000, 20000 - 56 - publication['world'][1]),
                'Native publication depth differs from the independently proven source formula')
    native = depth_queue.original_cohort_trace([publication['world'][1] for publication in publications])
    require(len(native['registration']) == 21 and len(native['states']) == len(publications),
            'Original depth queue did not preserve every publication')
    expected_ids = set(range(21))
    require(set(native['initial_draw_order']) == expected_ids, 'Initial original queue lost/duplicated a group')
    rows, position = {}, 0
    order = native['initial_draw_order']
    current_depth = 19812
    for row in case['trace']:
        for publication in row['publications']:
            state = native['states'][position]
            require((state['world_y'], state['depth']) == (publication['world'][1], publication['depth']) and
                    set(state['draw_order']) == expected_ids, 'Original queue publication sequence changed')
            order, current_depth = state['draw_order'], state['depth']
            position += 1
        require(current_depth == max(10000, 20000 - 56 - row['render_world'][1]),
                'Final original depth does not match the final published world position')
        rows[row['tick']] = {'draw_order': list(order), 'depth': current_depth,
                             'publication_offset': position}
    require(position == len(publications), 'Original queue did not consume all publications')
    return {'registration': native['registration'], 'initial_draw_order': native['initial_draw_order'],
            'rows': rows, 'publication_count': position, 'intercepted_functions': []}


def group_key(draw):
    if draw['kind'] == 'reef':
        return 'reef', draw['instance_id']
    require(draw['kind'] == 'ship', 'Unknown source draw kind')
    return ('shadow' if draw['detached'] else 'body'), draw['instance_id']


def checkpoint_reference(reference, case, stage, row):
    frame, (world_x, world_y) = row['drawn_frame'], row['render_world']
    parts = reference['poses'][frame]
    depth = max(10000, 20000 - 56 - world_y)
    groups = {}
    for draw in reference['draws']:
        updated = draw
        if draw['kind'] == 'ship' and draw['instance_id'] == 11:
            part = parts[draw['source_index']]
            updated = dict(draw, name=part['name'], image=part['image'], x=world_x + part['offset_x'],
                           y=world_y + part['offset_y'], depth=21000 if part['source_index'] == 0 else depth)
        groups.setdefault(group_key(updated), []).append(updated)
    queue = case['_native_queue']
    state = queue['rows'][row['tick']]
    require(state['depth'] == depth, 'Native queue/rendered parent depth disagree')
    draws, expected_queue, expected_queue_rows = [], [], []
    for node_id in state['draw_order']:
        group = queue['registration'][node_id]
        require(group['node_id'] == node_id, 'Native queue node mapping changed')
        identifier = int(group['resource_name'][4:], 16)
        kind = {'separate_shadow': 'shadow', 'inline_parent': 'body', 'reef': 'reef'}.get(group['kind'])
        require(kind is not None, 'Native queue references an unknown group kind')
        selected = groups[kind, identifier]
        group_depth = depth if kind == 'body' and identifier == 11 else group['depth']
        require(all(draw['depth'] == group_depth for draw in selected), 'Native group depth differs from selected parts')
        expected_queue.append(dict(group, depth=group_depth))
        for draw in selected:
            expected_queue_rows.append({'stage': stage, 'node': node_id, 'kind': group['kind'],
                                        'id': identifier, 'part': draw['source_index'] if draw['kind'] == 'ship' else -1,
                                        'depth': group_depth, 'order': len(draws) + 10})
            draws.append(draw)
    require(len(draws) == 34 and sum(draw['kind'] == 'ship' for draw in draws) == 29,
            'Native queue flattening lost a source group or part')
    alpha = Image.new('L', (56, 56))
    for part in parts.values():
        alpha = ImageChops.lighter(alpha, part['image'].getchannel('A'))
    ship = dict(reference['ships'][11], world_pixel=(world_x, world_y), cell=tuple(row['cell']), alpha=alpha,
                frame_index=frame, reference_depth=depth)
    ship['parts'] = [draw for draw in draws if draw['kind'] == 'ship' and draw['instance_id'] == 11]
    ships = dict(reference['ships']); ships[11] = ship
    result = {key: value for key, value in reference.items() if key != '_checkpoint_cache'}
    result.update(ships=ships, draws=draws)
    result['world'] = units.compose_world(result)
    result['expected_image'] = units.expected_image(result, CASE)
    result['regions'] = units.ship_regions(result, CASE)
    result['checkpoint'] = expected_stage(case, stage, row)
    result['expected_all_parts'] = [{'instance_id': draw['instance_id'], 'source_index': draw['source_index'],
                                    'sprite': draw['name'], 'order': index + 10,
                                    'position': [draw['x'], draw['y']]}
                                   for index, draw in enumerate(draws) if draw['kind'] == 'ship']
    result['expected_parts'] = [{key: value for key, value in part.items() if key != 'instance_id'}
                                for part in result['expected_all_parts'] if part['instance_id'] == 11]
    result['expected_queue'] = expected_queue
    result['expected_queue_rows'] = expected_queue_rows
    return result


def stage_records(log):
    result = []
    for line in log.splitlines():
        if not line.startswith(PREFIX + 'stage='):
            continue
        values = {}
        for token in line[len(PREFIX):].split(' '):
            require('=' in token, 'Malformed route stage token')
            key, value = token.split('=', 1)
            require(key not in values, 'Duplicated route stage field')
            if key in PAIR_FIELDS:
                require(re.fullmatch(r'-?\d+,-?\d+', value) is not None, 'Invalid route pair')
                value = [int(part) for part in value.split(',')]
            elif key in BOOL_FIELDS:
                require(value in ('True', 'False'), 'Invalid route boolean')
                value = value == 'True'
            elif key != 'stage':
                value = int(value)
            values[key] = value
        require(set(values) == set(STAGE_FIELDS), 'Missing/unknown route stage field')
        result.append(values)
    return result


def conditions_line(case):
    return (PREFIX + 'conditions: id=0000000b; origin=16,2; goal=' + ','.join(map(str, case['goal'])) +
            '; planner=source-line-wave-static-fleet; planner_counter=1; wind_force=0; wind_heading=5; '
            'owner_upgrade=0; quantum_ms=40; pending_steps=1; clock=bounded-single-step; '
            'input=domain-reference; full_simulation=False; sorting=source-normal-cohort')


def command_line(case):
    return (PREFIX + 'command: copied_bytes=26; target=' + ','.join(map(str, case['goal'])) +
            '; opaque_byte=255; promotion=Promoted; active_flags=128; pending_flags=0; route_byte=0; has_route=' +
            str(case['accepted']))


def path_line(case):
    return PREFIX + f"path: count={case['trace'][0]['path_count']}; points_hex={case['active_path_hex']}"


def completion_line(case, stop_at=None):
    if not case['accepted']:
        return PREFIX + 'rejected: goal=' + ','.join(map(str, case['goal'])) + '; calls=0; counter=1; no_route=True; frozen=True'
    last = case['trace'][-1]
    if stop_at is not None and stop_at < last['tick']:
        row = case['trace'][stop_at]
        return PREFIX + f"halted: calls={row['tick']}; counter={row['stamp']}; diagnostic_only=True"
    if not is_complete(case, last):
        return (PREFIX + 'stalled: goal=' + ','.join(map(str, case['goal'])) +
                f"; calls={last['tick']}; counter={last['stamp']}; target_reached=False; frozen=True")
    return (PREFIX + 'complete: goal=' + ','.join(map(str, case['goal'])) +
            f"; calls={last['tick']}; counter={last['stamp']}; frame={last['frame']}; drawn_frame={last['drawn_frame']}" +
            '; frozen_after_arrival=True; idle_rng=False')


def expected_registration(reference, case):
    counts = {}
    for draw in reference['draws']:
        key = group_key(draw)
        counts[key] = counts.get(key, 0) + 1
    result = []
    for group in case['_native_queue']['registration']:
        identifier = int(group['resource_name'][4:], 16)
        kind = {'separate_shadow': 'shadow', 'inline_parent': 'body', 'reef': 'reef'}[group['kind']]
        result.append({'node': group['node_id'], 'kind': group['kind'], 'id': identifier,
                       'depth': group['depth'], 'components': counts[kind, identifier]})
    return result


def queue_records(log):
    registration, queues = [], {}
    register_pattern = re.compile(re.escape(PREFIX) +
        r'registration: node=(\d+); kind=([^;]+); id=([0-9a-f]{8}); depth=(-?\d+); components=(\d+)')
    queue_pattern = re.compile(re.escape(PREFIX) +
        r'queue: stage=([a-z0-9-]+); node=(\d+); kind=([^;]+); id=([0-9a-f]{8}); part=(-?\d+); depth=(-?\d+); order=(-?\d+)')
    current_stage = None
    for line in log.splitlines():
        if line.startswith(PREFIX + 'stage='):
            current_stage = line.split('stage=', 1)[1].split(' ', 1)[0]
        if line.startswith(PREFIX + 'registration:'):
            match = register_pattern.fullmatch(line)
            require(match is not None, 'Malformed source queue registration')
            node, kind, identifier, depth, components = match.groups()
            registration.append({'node': int(node), 'kind': kind, 'id': int(identifier, 16),
                                 'depth': int(depth), 'components': int(components)})
        if line.startswith(PREFIX + 'queue:'):
            match = queue_pattern.fullmatch(line)
            require(match is not None, 'Malformed actual source queue order')
            stage, node, kind, identifier, part, depth, order = match.groups()
            require(stage == current_stage, 'Source queue order leaves/precedes its current stage')
            queues.setdefault(stage, []).append({'stage': stage, 'node': int(node), 'kind': kind,
                'id': int(identifier, 16), 'part': int(part), 'depth': int(depth), 'order': int(order)})
    return registration, queues


def validate_stage_log(log, reference, case, checkpoints, *, complete=False, stop_at=None):
    require('Exception' not in log and PREFIX + 'failed' not in log, 'Route player reported an exception/failure')
    command_seen = False
    for label, expected in (('conditions:', conditions_line(case)), ('command:', command_line(case))):
        lines = [line for line in log.splitlines() if line.startswith(PREFIX + label)]
        if label == 'command:' and not complete:
            require(lines in ([], [expected]), 'Duplicated/invalid route ' + label)
            command_seen = bool(lines)
        else:
            require(lines == [expected], 'Missing/duplicated/invalid route ' + label)
            if label == 'command:':
                command_seen = True
    paths = [line for line in log.splitlines() if line.startswith(PREFIX + 'path:')]
    require(paths in ([], [path_line(case)]), 'Duplicated/invalid source route path bytes')
    records = stage_records(log)
    require(not records or paths == [path_line(case)], 'Source checkpoint precedes its exact native path')
    if complete:
        require(paths == [path_line(case)], 'Missing source path bytes')
    registration, queue_rows = queue_records(log)
    expected_register = expected_registration(reference, case)
    require(registration == expected_register[:len(registration)] and len(registration) <= 21,
            'Source node registration changed, duplicated or became unordered')
    require(not records or registration == expected_register, 'Source stage precedes complete queue registration')
    expected_names = list(checkpoints)
    names = [record['stage'] for record in records]
    require(not names or command_seen, 'Route checkpoint precedes its command')
    require(names == expected_names[:len(names)] and len(names) <= len(expected_names),
            'Missing, duplicated or unordered route checkpoint')
    for record in records:
        require(record == checkpoints[record['stage']]['checkpoint'],
                'Route checkpoint differs from pinned native state: ' + record['stage'])
    pattern = re.compile(re.escape(PREFIX) + r'part: stage=([a-z0-9-]+); source_index=(\d+); sprite=([^;]+); order=(-?\d+); position=(-?\d+),(-?\d+)')
    parts = {name: [] for name in names}
    current_stage = None
    for line in log.splitlines():
        if line.startswith(PREFIX + 'stage='):
            current_stage = line.split('stage=', 1)[1].split(' ', 1)[0]
        if not line.startswith(PREFIX + 'part:'):
            continue
        match = pattern.fullmatch(line)
        require(match is not None, 'Malformed route renderer part declaration')
        name, index, sprite, order, x, y = match.groups()
        require(name in parts and name == current_stage, 'Route renderer part precedes/leaves its stage')
        parts[name].append({'source_index': int(index), 'sprite': sprite, 'order': int(order), 'position': [int(x), int(y)]})
    require(all(name in names for name in queue_rows), 'Source queue references an unknown stage')
    for index, name in enumerate(names):
        expected_queue = checkpoints[name]['expected_queue_rows']
        actual_queue = queue_rows.get(name, [])
        require(actual_queue == expected_queue[:len(actual_queue)] and len(actual_queue) <= 34,
                'Actual34-renderer order differs from the history of native depth updates')
        require(len({(part['id'], part['part']) for part in actual_queue}) == len(actual_queue),
                'Duplicate actual renderer queue entry')
        if complete or index < len(names) - 1:
            require(actual_queue == expected_queue, 'Missing actual renderer queue entries')
        expected, actual = checkpoints[name]['expected_parts'], parts[name]
        require(len({part['source_index'] for part in actual}) == len(actual), 'Duplicate route part declaration')
        require(all(part in expected for part in actual), 'Route part differs from native pose/order/anchor')
        if complete or index < len(names) - 1:
            require(sorted(actual, key=lambda part: part['source_index']) == sorted(expected, key=lambda part: part['source_index']),
                    'Missing route renderer part declaration')
    if complete:
        require(names == expected_names, 'Incomplete route checkpoint sequence')
        endings = [line for line in log.splitlines() if any(line.startswith(PREFIX + label)
                   for label in ('complete:', 'halted:', 'rejected:', 'stalled:'))]
        require(endings == [completion_line(case, stop_at)], 'Missing/invalid route ending')
        row = case['trace'][min(stop_at, len(case['trace']) - 1) if stop_at is not None else -1]
        cleanup = f"Mission unit reference cleanup: claimed_released={row['occupied_cell_count']}; visual_refs_cleared=True"
        require([line for line in log.splitlines() if line.startswith('Mission unit reference cleanup:')] == [cleanup],
                'Route run did not release its native source claims and visual references')
        require(movement.DIAGNOSTIC_EXIT in log, 'Route timed diagnostic exit marker missing')
    return {'stages': records, 'parts': parts, 'registration': registration, 'queue': queue_rows}


