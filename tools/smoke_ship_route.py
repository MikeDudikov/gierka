def native_cases(fixture):
    cases = [case for case in fixture['cases'] if case['scenario'] == 'source_static' and
             case['controlled_inputs']['pending_steps_each_call'] == 1 and tuple(case['goal']) in GOALS]
    require(len(cases) == len(GOALS) and {tuple(case['goal']) for case in cases} == set(GOALS),
            'Native route fixture does not contain exactly one canonical pending1 trace per goal')
    by_goal = {tuple(case['goal']): dict(case) for case in cases}
    require([by_goal[goal]['accepted'] for goal in GOALS] == [True, True, True, True, False, True],
            'Native route accepted/rejected cohort changed')
    for goal in GOALS:
        case = by_goal[goal]
        require(case['source_resource'] == 'OBJ_0000000b', 'Native route request identity changed')
        conditions = case['controlled_inputs']
        require(all(conditions[key] == value for key, value in
                    {'pending_steps_each_call': 1, 'wind_strength': 0, 'wind_heading': 5,
                     'owner_upgrade_byte': 0}.items()), 'Native route controlled conditions changed')
        require(case['trace'][0]['stamp'] == 1 and case['trace'][0]['tick'] == 0 and
                case['trace'][0]['world'] == [1028, 132] and case['trace'][0]['drawn_frame'] == 20,
                'Native route initial counter/publication phase changed')
        for index, row in enumerate(case['trace']):
            require(row['tick'] == index and row['stamp'] == index + 1,
                    'Native route call and source-counter relationship changed')
            require(0 <= row['drawn_frame'] < 88 and row['occupied_cell_count'] in (8, 9),
                    'Native route sprite/occupancy trace exceeds diagnostic scope')
            require(bool(row['pose_published']) == bool(row['publications']) and len(row['publications']) <= 2,
                    'Native route publication flag/count disagree')
        if case['accepted']:
            require(len(case['native_navigation']['points']) > 2,
                    'Canonical long route unexpectedly became an adjacent route')
            require(case['trace'][-1]['state'] == 0 and (goal == (19, 4) or
                    case['trace'][-1]['cell'] == list(goal) and
                    case['trace'][-1]['world'] == [goal[0] * 64 + 4, goal[1] * 64 + 4]),
                    'Native route did not arrive at its physical target anchor')
        else:
            require(len(case['trace']) == 1 and not case['active_path_hex'],
                    'Rejected native route request acquired movement steps/path')
        case['_native_queue'] = native_queue_history(case)
    return by_goal


