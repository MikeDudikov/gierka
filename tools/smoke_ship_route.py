def stage_plan(case, stop_at=None):
    require(stop_at is None or isinstance(stop_at, int) and not isinstance(stop_at, bool) and 0 <= stop_at <= 2048,
            'Route stop count must be0..2048 or absent')
    trace = case['trace']
    result = [('initial', trace[0])]
    if not case['accepted']:
        return result + [('rejected', trace[0])]
    points = case['native_navigation']['points']
    require(len(points) == len({tuple(point[:2]) for point in points}),
            'Runtime source event labeling requires the verified routes without revisited cells')
    cell_indices = {tuple(point[:2]): index for index, point in enumerate(points)}
    flat_indices = {point[1] * 24 + point[0]: index for index, point in enumerate(points)}
    seen = set()
    previous = trace[0]
    for row in trace[1:]:
        if stop_at is not None and row['tick'] > stop_at:
            break
        active = previous['path_index']
        conditions = (
            ('turn-start', active, 32 <= row['frame'] <= 55),
            ('turn-published', active, bool(row['publications']) and row['state'] == 2),
            ('turn-complete', active, previous['state'] == 2 and row['state'] == 3),
            ('reserved', flat_indices.get(row['reserved'], -1), row['reserved'] >= 0),
            ('first-pixel', active, row['world'] != previous['world']),
            ('transferred', cell_indices.get(tuple(row['cell']), -1), row['cell'] != previous['cell']),
            ('waypoint', active, row['path_index'] > active),
        )
        for event, index, condition in conditions:
            name = event + '-' + str(index)
            if condition and name not in seen:
                require(1 <= index < len(points), 'Native source event left its path point sequence')
                seen.add(name)
                result.append((name, row))
        if row['state'] == 0:
            result.append(('arrived' if is_complete(case, row) else 'stalled', row))
        previous = row
    return result


def is_complete(case, row):
    return bool(case['accepted'] and row['state'] == 0 and row['cell'] == list(case['goal']) and
                row['world'] == [case['goal'][0] * 64 + 4, case['goal'][1] * 64 + 4])


