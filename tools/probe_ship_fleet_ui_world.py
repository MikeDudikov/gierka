"""First UI fleet release matched to the source world mail/task lifecycle.

Actual UI release runs in its existing separate source engine. Its immutable
41/20 packets must equal those generated by49ca60/4ccc30 in WorldOracle.
The latter engine then runs clock/mail/fleet/three ship Work together. This
is a checked UI/world boundary,not a single fully initialized original app.
"""
from pathlib import Path
import argparse,json
from tools import probe_ship_fleet_input_cycle as ui,probe_ship_world_step as world
ROOT=world.ROOT


def fixture():
    #49ecb0 releases,49ca60 commit,4ccc30 normal request and520c50 serialization.
    cursor=ui.dispatch.MoveOracle(ui.dispatch.membership.hover.source_metadata());selection=[]
    for kind,target,flags in((5,11,0),(5,12,4),(5,13,4),(7,None,0)):
        cursor.selection_events.clear();selection.append(cursor.release(kind,target,flags=flags))
    packets=[dict(p)for p in cursor.commands]
    cases=[]
    for order in((-1,11,12,13),(11,-1,12,13),(11,12,-1,13),(11,12,13,-1)):
        for warm in(0,1,2):
            engine=world.WorldOracle(order,warm)
            initial=[engine.live_snapshot(i)for i in world.live.LOCAL]
            engine.request()
            queued=engine.queued()
            assert [dict(actor=p['actor'],action=p['action'],payload_hex=p['payload_hex'])for p in queued]==packets
            assert all(p['counter']==0 for p in queued)
            rows=[dict(engine.frame(t*40),notified=False)for t in range(1,201)]
            receipt=next(r for r in rows if r['received'])
            assert receipt['counter']==3-warm and len(receipt['received'])==6
            assert not any(r['emitted']for r in rows) #No synthetic member300 events in this UI case.
            cases.append(dict(label='ui-world-'+str(order.index(-1))+'-'+str(warm),order=order,warm=warm,
                members=world.live.LOCAL,initial=initial,queued=queued,rows=rows))
    return dict(schema_version=1,original_exe_sha256=world.original.EXPECTED,selection=selection,packets=packets,cases=cases,
        seed_payloads={str(i):engine.records[i].hex()for i in world.live.LOCAL},
        terrain=list(world.live.motion.original.struct.unpack('<576h',bytes(engine.u.mem_read(engine.r(0x5c93bc),1152)))),scope=__doc__)


def main():
    p=argparse.ArgumentParser();p.add_argument('--output',type=Path,required=True);a=p.parse_args()
    data=fixture();a.output.write_text(json.dumps(data,separators=(',',':'))+'\n')
    print(dict(cases=len(data['cases']),frames=sum(len(c['rows'])for c in data['cases'])))


if __name__=='__main__':main()
