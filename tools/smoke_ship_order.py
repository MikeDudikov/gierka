def can_request(sample):
    return sample['state'] == 0 and not (sample['active'] & 0x80) and not (sample['pending'] & 0x88)


def path_complete(sample):
    end = sample['path_endpoint']
    return bool(sample['path_count'] > 0 and end != [-1, -1] and sample['state'] == 0 and
                sample['cell'] == end and sample['world'] == [end[0] * 64 + 4, end[1] * 64 + 4])


def requested_reached(sample):
    target = sample['active_target']
    return bool(sample['state'] == 0 and sample['cell'] == target and
                sample['world'] == [target[0] * 64 + 4, target[1] * 64 + 4])


def native_cases(fixture):
    result = {}
    for source in fixture['cases']:
        if source['session_seed'] != 0 or source['pending_steps'] != 1:
            continue
        case = dict(source)
        case['samples'] = [dict(sample) for sample in source['samples']]
        case['trace'] = [dict(sample, tick=sample['sample_index']) for sample in source['samples']]
        for index, sample in enumerate(case['samples']):
            require(sample['sample_index'] == index and sample['stamp'] == sample['counter'] == sample['tick'],
                    'Native order sample/counter identity changed')
            require(sample['operation'] in ('initial', 'request', 'tick') and
                    0 <= sample['drawn_frame'] < 88 and sample['occupied_cell_count'] in (8, 9),
                    'Native order operation, pose or occupancy left its supported scope')
            require(bool(sample['publications']) == bool(sample['pose_published']),
                    'Native order publication flag/count disagree')
            if index:
                previous = case['samples'][index - 1]
                require(sample['counter'] == previous['counter'] + (sample['operation'] == 'tick'),
                        'A source request incorrectly advanced its source counter')
                if sample['operation'] == 'request':
                    require(not sample['publications'] and not sample['animation_tail_reached'] and
                            all(sample[key] == previous[key] for key in
                                ('frame', 'drawn_frame', 'world', 'render_world', 'random_state', 'last_frame_tick')),
                            'A source request mutated motion, idle RNG or presentation')
        require(case['samples'][0]['operation'] == 'initial' and case['samples'][0]['counter'] == 0 and
                case['samples'][0]['world'] == [1028, 132] and case['samples'][0]['drawn_frame'] == 20,
                'Native order did not begin with the verified source0b initial snapshot')
        case['_native_queue'] = native_queue_history(case)
        result[case['label']] = case
    require('reach18_5' in result, 'Native order fixture lacks its normal movement cycle')
    return result


