EVENT_FAMILIES = ('promoted', 'path', 'turn', 'reserved', 'moving', 'transferred',
                  'path-complete', 'stop-request', 'active-cleared', 'idle-published')


def stage_plan(case, stop_at=None):
    require(stop_at is None or isinstance(stop_at, int) and not isinstance(stop_at, bool) and 0 <= stop_at <= 4096,
            'Normal-order stop counter must be0..4096 or absent')
    events, observed = [], set()
    previous = None
    last = None
    for sample in case['samples']:
        if stop_at is not None and sample['counter'] > stop_at:
            break
        last = sample
        if sample['operation'] == 'initial':
            events.append(('initial', sample))
        elif sample['operation'] == 'request':
            events.append(('request-' + str(sample['epoch']), sample))
        else:
            require(previous is not None, 'Native tick precedes the initial snapshot')
            idle = can_request(sample) and bool(sample['publications']) and 56 <= sample['drawn_frame'] <= 87
            conditions = (
                bool(sample['active'] & 0x80), sample['path_count'] > 0,
                bool(sample['publications']) and sample['state'] == 2,
                sample['reserved'] >= 0, sample['world'] != previous['world'], sample['cell'] != previous['cell'],
                path_complete(sample), bool(sample['pending'] & 8),
                bool(previous['active'] & 0x80) and not (sample['active'] & 0x80), idle,
            )
            for name, condition in zip(EVENT_FAMILIES, conditions):
                stage = name + '-' + str(sample['epoch'])
                if condition and stage not in observed:
                    observed.add(stage)
                    events.append((stage, sample))
            if stop_at is not None and sample['counter'] == stop_at:
                events.append(('halted', sample))
                return events
            if idle and sample['epoch'] == len(case['goals']):
                return events
        previous = sample
    require(last is not None, 'Empty native normal-order sequence')
    if stop_at is not None:
        require(last['counter'] == stop_at, 'Native fixture does not reach the requested order stop counter')
        events.append(('halted', last))
    return events


